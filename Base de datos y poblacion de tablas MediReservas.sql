-- Servicio: auth | Base original: auth_db
-- ============================================================
-- Origen: backend/auth/src/main/resources/db/migration/V1__create_auth_tables.sql
CREATE TABLE auth_users (
    auth_user_id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY (START WITH 303) PRIMARY KEY,
    email VARCHAR2(100 CHAR) NOT NULL UNIQUE,
    password_hash VARCHAR2(255 CHAR) NOT NULL,
    enabled NUMBER(1) DEFAULT 1 NOT NULL CHECK (enabled IN (0, 1)),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE roles (
    role_id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY (START WITH 5) PRIMARY KEY,
    role_name VARCHAR2(50 CHAR) NOT NULL UNIQUE,
    description VARCHAR2(255 CHAR),
    active NUMBER(1) DEFAULT 1 NOT NULL CHECK (active IN (0, 1))
);

CREATE TABLE auth_user_roles (
    auth_user_id NUMBER(19) NOT NULL,
    role_id NUMBER(19) NOT NULL,

    PRIMARY KEY (auth_user_id, role_id),

    CONSTRAINT fk_auth_user_roles_auth_user
        FOREIGN KEY (auth_user_id)
        REFERENCES auth_users(auth_user_id),

    CONSTRAINT fk_auth_user_roles_role
        FOREIGN KEY (role_id)
        REFERENCES roles(role_id)
);

