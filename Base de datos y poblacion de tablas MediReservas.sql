    end_time VARCHAR2(8 CHAR) NOT NULL CHECK (REGEXP_LIKE(end_time, '^([01][0-9]|2[0-3]):[0-5][0-9]:[0-5][0-9]$')),
    slot_status VARCHAR2(30 CHAR) NOT NULL,
    appointment_id NUMBER(19),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT uq_doctor_slot
        UNIQUE (doctor_id, slot_date, start_time, end_time)
