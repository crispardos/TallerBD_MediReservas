CREATE TABLE doctor_schedules (
    doctor_schedule_id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY (START WITH 6) PRIMARY KEY,
    doctor_id NUMBER(19) NOT NULL,
    day_of_week VARCHAR2(20 CHAR) NOT NULL,
    start_time VARCHAR2(8 CHAR) NOT NULL CHECK (REGEXP_LIKE(start_time, '^([01][0-9]|2[0-3]):[0-5][0-9]:[0-5][0-9]$')),
    end_time VARCHAR2(8 CHAR) NOT NULL CHECK (REGEXP_LIKE(end_time, '^([01][0-9]|2[0-3]):[0-5][0-9]:[0-5][0-9]$')),
    active NUMBER(1) DEFAULT 1 NOT NULL CHECK (active IN (0, 1))
