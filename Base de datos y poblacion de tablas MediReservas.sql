-- MediReservasApp: estructura y datos iniciales para Oracle 19c / 21c.
-- Adaptacion de las 17 migraciones de los 11 servicios del backend.
-- Las 31 tablas se crean en el esquema del usuario conectado.
-- Ejecutar una sola vez en un esquema sin estas tablas, con CREATE TABLE
-- y cuota de tablespace suficiente. No ejecutar como SYS.
-- En SQL Developer ejecutar como script (F5).
-- Los nombres de bases originales se conservan solo como referencia.
-- Horarios start_time/end_time: texto HH24:MI:SS validado (00:00:00 a 23:59:59).
-- Booleanos: NUMBER(1), con 1 = verdadero y 0 = falso.
-- Identidades con IDs iniciales explicitos comienzan despues del mayor ID cargado.
-- No incluye historial Flyway ni datos de instancias en ejecucion.
-- El backend original sigue configurado para MySQL; este script no lo migra.

SET DEFINE OFF;

